#include "FrameWork.h"

// アプリケーション全体の実行手順を管理する。
// virtual関数の呼び出しでは、派生クラスでオーバーライドした処理が実行される。
void FrameWork::Run() {
	// メインループに入る前に、一度だけ初期化する。
	Initialize();

	while (true) {

		// 入力やゲーム状態などを更新する。
		Update();

		// 更新後に終了要求を確認する。
		// 終了が要求されたフレームでは、Drawを呼ばずにループを抜ける。
		if (IsEndRequest()) {
			break;
		}

		// 終了要求がなければ描画する。
		Draw();
	}

	// メインループ終了後に、一度だけ終了処理を行う。
	Finalize();
}

// 基底クラスでは初期化処理を行わない。
// 必要な処理は派生クラスでオーバーライドして実装する。
void FrameWork::Initialize() {}

// 基底クラスでは更新処理を行わない。
// 必要な処理は派生クラスでオーバーライドして実装する。
void FrameWork::Update() {}

// 基底クラスでは終了処理を行わない。
// 必要な処理は派生クラスでオーバーライドして実装する。
void FrameWork::Finalize() {}